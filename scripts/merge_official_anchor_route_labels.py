#!/usr/bin/env python3
"""Combine verified baselines and public-anchor labels without mixing SC routes.

Public-anchor SC labels were generated by CheatCode, not Low Lateral Bypass.
They are excluded from the active union. Raw labels remain as diagnostics.
"""
import argparse
from collections import defaultdict
import hashlib
import json
from pathlib import Path

VERIFIED_LLB_SC_SHA='c2a984ce522d30ec84e116036fa87f838ecf86b51eb9b9b1deaf5ffd464da653'


def digest(path):
    h=hashlib.sha256()
    with path.open('rb') as stream:
        for block in iter(lambda:stream.read(1<<20),b''):h.update(block)
    return h.hexdigest()


def append(source,out,episode_scenes,counts):
    with source.open() as inp:
        for line in inp:
            row=json.loads(line)
            if row['split'] not in ('train','validation'):raise ValueError('Unexpected split')
            scene=row['scene_sha256'];split=row['split']
            previous=episode_scenes.get(scene)
            if previous is not None and previous!=split:
                raise ValueError(f'Scene leak {scene}: {previous} vs {split}')
            episode_scenes[scene]=split
            counts[split].add(row['episode_index'])
            out.write(line if line.endswith('\n') else line+'\n')


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--base-sfp',type=Path,required=True)
    p.add_argument('--base-sc',type=Path,required=True)
    p.add_argument('--anchor-labels',type=Path,action='append',required=True)
    p.add_argument('--output',type=Path,required=True)
    a=p.parse_args()
    if digest(a.base_sc)!=VERIFIED_LLB_SC_SHA:
        p.error('SC base source differs from verified cleaned LLB labels; route audit required')
    if a.output.exists():p.error('Preserve immutable union')
    a.output.mkdir(parents=True)
    result={}
    for family,base,filename in (('sfp',a.base_sfp,'sfp_transport_chunks.jsonl'),
                                 ('sc',a.base_sc,'sc_transport_chunks.jsonl')):
        scenes={};counts=defaultdict(set)
        destination=a.output/f'{family}_labels.jsonl'
        anchors=([folder/filename for folder in a.anchor_labels]
                 if family=='sfp' else [])
        with destination.open('w') as out:
            append(base,out,scenes,counts)
            for anchor in anchors:append(anchor,out,scenes,counts)
        result[family]=dict(source_hashes={str(path):digest(path) for path in (base,*anchors)},
                            episodes={key:len(value) for key,value in counts.items()},
                            reset_groups=len(scenes),output=str(destination),
                            output_sha256=digest(destination),
                            excluded_anchor_sources=([str(folder/filename) for folder in a.anchor_labels]
                                                     if family=='sc' else []),
                            route_policy=('cheatcode_sfp_admitted' if family=='sfp'
                                          else 'llb_only; public_anchor_cheatcode_sc_excluded'))
    (a.output/'manifest.json').write_text(json.dumps(dict(
        schema='aic_official_anchor_route_union/v1',families=result,
        complete_reset_split=True,final_scenes_opened=False),indent=2)+'\n')
    print(json.dumps(result),flush=True)


if __name__=='__main__':main()
